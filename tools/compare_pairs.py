"""Compare related documents: shared wording (template reuse) and differing numbers (conflicts).

  python tools/compare_pairs.py  -> docs/pair_comparisons.md
Pairs are fixed in PAIRS below; each was linked during verification (same provider, or near-identical text).
"""
import re, sys
from difflib import SequenceMatcher
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent.parent))
from promise_card.clauses import sentences
from promise_card.contradictions import amounts
from promise_card.quote_check import norm

PAIRS = [("L05", "L06", "same provider, same programme name"),
         ("L01b", "L26", "same provider (terms page vs programme document)"),
         ("L19", "L20", "two brands, similar FAQ"),
         ("L07", "L08", "two providers, similar policy"),
         ("P09", "P09b", "same provider, two pages")]


def sents(doc):
    t = Path(f"data/sources/{doc}.txt").read_text(encoding="utf-8")
    return [s for s in sentences(t) if len(norm(s)) >= 40]


def shared(a, b, thr=0.85):
    out = []
    for x in a:
        nx = re.sub(r"[^a-z0-9 ]", "", norm(x))
        best = max(((SequenceMatcher(None, nx, re.sub(r"[^a-z0-9 ]", "", norm(y))).ratio(), y) for y in b), default=(0, ""))
        if best[0] >= thr:
            out.append((round(best[0], 2), x, best[1]))
    return out


lines = ["# Pair comparisons (generated by tools/compare_pairs.py)\n",
         "Similarity is sentence-level (0-1, after lower-casing and removing punctuation); 1.0 = identical wording.\n"]
for a, b, why in PAIRS:
    sa, sb = sents(a), sents(b)
    sh = shared(sa, sb)
    lines.append(f"## {a} vs {b} ({why})\n")
    lines.append(f"- Sentences of 40+ characters: {a} {len(sa)}, {b} {len(sb)}; near-identical (≥0.85): **{len(sh)}**\n")
    for r, x, y in sh[:12]:
        lines.append(f"  - ({r}) {a}: “{x[:160]}”<br>{b}: “{y[:160]}”")
    lines.append("")
_B = re.compile(r"\b(?:" + "|".join(l.strip() for l in Path("data/private_brands.txt").read_text(encoding="utf-8").splitlines() if l.strip()) + r")\b", re.I)
lines = [_B.sub("[Provider]", l) for l in lines]
Path("docs/pair_comparisons.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(l for l in lines if l.startswith(("##", "- "))))

# --- differing numbers between hand-label quotes, per field ----------------------------
import csv
lab = {r["offer_id"]: r for r in csv.DictReader(open("data/labels.csv", encoding="utf-8"))}
F = ["total_cost", "payment_timing", "promise", "conditions", "terms_can_change", "if_not_placed", "refuse_offer", "terms_elsewhere"]
extra = ["\n# Differing numbers in the same field (from hand-labelled quotes)\n"]
for a, b, why in PAIRS:
    if a not in lab or b not in lab:
        continue
    for f in F:
        qa, qb = lab[a][f + "_quote"] or "", lab[b][f + "_quote"] or ""
        ma, mb = amounts(qa), amounts(qb)
        for kind in sorted(set(ma) & set(mb)):
            only_a, only_b = sorted(ma[kind] - mb[kind]), sorted(mb[kind] - ma[kind])
            if only_a and only_b:
                extra.append(f"- **{a} vs {b}, {f}** ({kind}): only in {a} {only_a}; only in {b} {only_b}")
Path("docs/pair_comparisons.md").write_text(Path("docs/pair_comparisons.md").read_text(encoding="utf-8") + "\n".join(extra) + "\n", encoding="utf-8")
print("\n".join(extra))
